#!/usr/bin/env node
/**
 * Renders docs/REGULATORY_CALENDAR.md from the regulatory register
 * (GLOBAL_FRAMEWORKS in src/compliance/globalRegulatory.ts).
 *
 * The calendar states only what the register records. An entry without
 * `sources` has an effective date nobody in the register checked against an
 * official text, so it renders as unverified. Optional fields a dated register
 * adds (status, lastReviewed, verified, unverifiedReason, sources,
 * obligations) render when present and are simply absent when not.
 *
 * The source is loaded through tsx (already a devDependency) so the calendar
 * follows src, not a possibly stale dist/; dist/ is the fallback.
 *
 * Usage: node scripts/gen-regulatory-calendar.mjs [--check] [--data <register.json>] [--out <file.md>]
 *   --check  exit 1 if the calendar differs from a fresh render (drift), 0 if equal
 *   --data   render a JSON register (an array, or {frameworks: [...]}) instead of src
 *   --out    calendar path (default docs/REGULATORY_CALENDAR.md)
 * Exit 2 means the register could not be loaded or is malformed.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const REGISTER_SRC = "src/compliance/globalRegulatory.ts";
const REGISTER_DIST = "dist/compliance/globalRegulatory.js";
const DEFAULT_OUT = "docs/REGULATORY_CALENDAR.md";

const cell = (v) => String(v).replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const present = (v) => v !== undefined && v !== null && String(v).trim() !== "";
const orDash = (v) => (present(v) ? cell(v) : "—");
const DATE_KEYS = ["appliesFrom", "date", "effectiveDate"];
const LABEL_KEYS = ["title", "label", "description", "article"];
const pick = (o, keys) => keys.map((k) => o?.[k]).find(present);

function validate(frameworks) {
  if (!Array.isArray(frameworks)) throw new TypeError("register must be an array of frameworks");
  frameworks.forEach((f, i) => {
    if (!f || typeof f !== "object" || !present(f.frameworkId)) throw new TypeError(`framework #${i} has no frameworkId`);
  });
}

function verification(f) {
  const sources = Array.isArray(f.sources) ? f.sources : [];
  if (f.verified === false) return `unverified${present(f.unverifiedReason) ? ` (${cell(f.unverifiedReason)})` : ""}`;
  if (sources.length === 0) return "unverified (no source in register)";
  return f.verified === true ? "verified" : "sourced";
}

function sourceList(f) {
  const sources = Array.isArray(f.sources) ? f.sources : [];
  if (sources.length === 0) return ["- Sources: none recorded in the register."];
  return sources.map((s) => `- Source: ${orDash(s?.title)} — <${s?.url ?? ""}>${present(s?.retrievedAt) ? `, retrieved ${cell(s.retrievedAt)}` : ", retrieval date not recorded"}`);
}

function dateOf(f) {
  return present(f.effectiveDate) ? String(f.effectiveDate) : null;
}

/** Earliest first; unknown dates last; ties broken by frameworkId so output is stable. */
function byDate(a, b) {
  const da = dateOf(a), db = dateOf(b);
  if (da !== db) return da === null ? 1 : db === null ? -1 : da < db ? -1 : 1;
  return String(a.frameworkId) < String(b.frameworkId) ? -1 : 1;
}

export function renderCalendar(frameworks) {
  validate(frameworks);
  const sorted = [...frameworks].sort(byDate);
  const reqs = sorted.reduce((n, f) => n + (Array.isArray(f.keyRequirements) ? f.keyRequirements.length : 0), 0);
  const unverified = sorted.filter((f) => verification(f).startsWith("unverified")).length;
  const out = [
    "# Regulatory calendar",
    "",
    "<!-- Generated by scripts/gen-regulatory-calendar.mjs. Do not edit by hand. -->",
    "<!-- Regenerate: node scripts/gen-regulatory-calendar.mjs   Drift check: node scripts/gen-regulatory-calendar.mjs --check -->",
    "",
    `Source: \`GLOBAL_FRAMEWORKS\` in \`${REGISTER_SRC}\` — ${sorted.length} frameworks, ${reqs} key requirements; ${unverified} of ${sorted.length} frameworks are unverified.`,
    "",
    "## How to read this calendar",
    "",
    "- Every date, status and mapping below is copied from the register. This page adds nothing the register does not record.",
    "- **Verification** is `unverified` when the register entry carries no official source, or marks itself unverified. Treat such a date as a lead to check, not as a fact.",
    "- `mappingStatus` and each requirement's `complianceStatus` are declared by the register's authors. They are not audit results and say nothing about any deployed agent.",
    "- This page is not legal advice.",
    "",
    "## Timeline",
    "",
    "| Effective date | Framework | Jurisdiction | Register status | Last reviewed | Verification | Declared mapping |",
    "|---|---|---|---|---|---|---|"
  ];
  for (const f of sorted) {
    out.push(`| ${dateOf(f) ? cell(dateOf(f)) : "unknown"} | ${orDash(f.name)} (\`${cell(f.frameworkId)}\`) | ${orDash(f.jurisdiction)} | ${orDash(f.status)} | ${orDash(f.lastReviewed)} | ${verification(f)} | ${orDash(f.mappingStatus)} |`);
  }
  const dated = sorted.flatMap((f) => (Array.isArray(f.obligations) ? f.obligations : [])
    .map((o) => ({ f, date: pick(o, DATE_KEYS), label: pick(o, LABEL_KEYS) })));
  if (dated.length > 0) {
    out.push("", "## Dated obligations", "", "| Applies from | Framework | Obligation |", "|---|---|---|");
    dated.sort((a, b) => (present(a.date) ? String(a.date) : "~").localeCompare(present(b.date) ? String(b.date) : "~"));
    for (const d of dated) out.push(`| ${present(d.date) ? cell(d.date) : "unknown"} | \`${cell(d.f.frameworkId)}\` | ${orDash(d.label)} |`);
  }
  out.push("", "## Frameworks", "");
  for (const f of sorted) {
    out.push(`### ${orDash(f.name)} (\`${cell(f.frameworkId)}\`)`, "");
    out.push(`- Jurisdiction: ${orDash(f.jurisdiction)}`, `- Effective date (as recorded): ${dateOf(f) ? cell(dateOf(f)) : "unknown"}`);
    out.push(`- Verification: ${verification(f)}`, ...sourceList(f), "");
    const rs = Array.isArray(f.keyRequirements) ? f.keyRequirements : [];
    if (rs.length === 0) { out.push("No key requirements recorded.", ""); continue; }
    out.push("| Requirement | Article | Title | AMC mapping (declared) | Evidence type | Declared status |", "|---|---|---|---|---|---|");
    for (const r of rs) {
      out.push(`| \`${cell(r?.requirementId ?? "—")}\` | ${orDash(r?.article)} | ${orDash(r?.title)} | ${present(r?.amcMapping) ? `\`${cell(r.amcMapping)}\`` : "—"} | ${orDash(r?.evidenceType)} | ${orDash(r?.complianceStatus)} |`);
    }
    out.push("");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

/**
 * dist/ is used only when tsx itself is not installed. If tsx is present but
 * src fails to load, that error stands: falling back would let a stale build
 * pass --check while src is broken.
 */
async function loadRegister(root) {
  let tsImport;
  try {
    ({ tsImport } = await import("tsx/esm/api"));
  } catch {
    const built = join(root, REGISTER_DIST);
    if (!existsSync(built)) throw new Error(`tsx is not installed and ${REGISTER_DIST} is missing; run pnpm install or pnpm build`);
    return (await import(pathToFileURL(built).href)).GLOBAL_FRAMEWORKS;
  }
  return (await tsImport(pathToFileURL(join(root, REGISTER_SRC)).href, import.meta.url)).GLOBAL_FRAMEWORKS;
}

function argValue(args, flag) {
  const i = args.indexOf(flag);
  return i >= 0 ? args[i + 1] : undefined;
}

async function main(args) {
  const root = process.cwd();
  const outPath = resolve(root, argValue(args, "--out") ?? DEFAULT_OUT);
  const dataPath = argValue(args, "--data");
  let next;
  try {
    let register;
    if (dataPath) {
      const raw = JSON.parse(readFileSync(resolve(root, dataPath), "utf8"));
      register = Array.isArray(raw) ? raw : raw?.frameworks;
    } else {
      register = await loadRegister(root);
    }
    next = renderCalendar(register);
  } catch (error) {
    console.error(`gen-regulatory-calendar: ${error.message}`);
    return 2;
  }
  if (args.includes("--check")) {
    const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
    if (current !== next) {
      console.error(`${outPath} is stale or hand-edited. Run: node scripts/gen-regulatory-calendar.mjs`);
      return 1;
    }
    console.log(`Regulatory calendar matches the register (${outPath}).`);
    return 0;
  }
  writeFileSync(outPath, next);
  console.log(`Wrote ${outPath}`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = await main(process.argv.slice(2));
}
