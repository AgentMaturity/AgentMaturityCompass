#!/usr/bin/env node
/**
 * Renders docs/adapters/SUPPORT_MATRIX.md from the adapter claim manifests (docs/adapters/manifests/*.json) and the
 * qualification records they cite (P2-17). Reads dist/ (build first). A manifest that claims more than its record
 * supports fails both modes, so the matrix never shows an unbacked claim.
 *
 *   node scripts/gen-harness-matrix.mjs --write   rewrite the matrix
 *   node scripts/gen-harness-matrix.mjs --check   fail when the committed matrix differs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const OUT = "docs/adapters/SUPPORT_MATRIX.md";
const ENTRY = "dist/adapters/conformance/adapterManifest.js";

const code = (value) => `\`${value}\``;
const list = (values) => (values.length > 0 ? values.join(", ") : "none");

function status({ manifest }) {
  const enforced = manifest.hooks.filter((hook) => hook.role === "enforce");
  // An enforce hook without a qualified version never reaches here: checkAdapterManifest refuses it.
  if (enforced.length > 0) return "enforced at listed hooks";
  if (manifest.harness.versions.length > 0) return "observe only";
  return manifest.hooks.length > 0 ? "observe only, no qualified version" : "unsupported: not qualified";
}

function renderMatrix(checked) {
  const lines = [
    "# Harness support matrix",
    "",
    "<!-- Generated by scripts/gen-harness-matrix.mjs from docs/adapters/manifests/*.json. Do not edit by hand. -->",
    "",
    "What AMC claims for each agent harness, from its adapter claim manifest. An adapter claims enforcement only at the",
    "hooks listed as enforced, and only at the qualified versions; every enforced hook is backed by passing cases in the",
    "cited qualification record. Everything else is observed or not covered. The support policy is in",
    "[SUPPORT_POLICY.md](SUPPORT_POLICY.md).",
    "",
    "| Harness | Package | Qualified versions | Enforced at | Observed at | Status | Qualification record |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const entry of checked) {
    const { manifest } = entry;
    const hooks = (role) => list(manifest.hooks.filter((hook) => hook.role === role).map((hook) => code(hook.name)));
    const versions = list(manifest.harness.versions) + (manifest.harness.commit ? ` (source pin ${code(manifest.harness.commit.slice(0, 8))})` : "");
    const record = manifest.receipt ? `${code(manifest.receipt)} (${manifest.qualifiedAt}, sha256 ${code(entry.receiptSha256.slice(0, 12))})` : "none";
    lines.push(`| ${manifest.adapter} | ${code(manifest.harness.package)} | ${versions} | ${hooks("enforce")} | ${hooks("observe")} | ${status(entry)} | ${record} |`);
  }
  lines.push("", "## Per hook", "");
  for (const { manifest } of checked) {
    lines.push(`### ${manifest.adapter}`, "");
    if (manifest.hooks.length > 0) {
      lines.push("| Hook | Role | Tools | On hook failure | Backing cases | Contract |", "|---|---|---|---|---|---|");
      for (const hook of manifest.hooks) {
        lines.push(`| ${code(hook.name)} | ${hook.role} | ${list(hook.tools)} | ${hook.onFailure} | ${list(hook.cases.map((item) => code(item.id)))} | ${hook.source} |`);
      }
      lines.push("");
    }
    lines.push("Not covered:", "", ...manifest.notCovered.map((item) => `- ${item}`), "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

async function main(argv) {
  if (!existsSync(ENTRY)) throw new Error(`Build first: ${ENTRY} not found (npm run build).`);
  const { loadAdapterManifests } = await import(pathToFileURL(ENTRY).href);
  const checked = loadAdapterManifests(process.cwd());
  const problems = checked.flatMap((entry) => entry.problems);
  if (problems.length > 0) {
    console.error(`adapter manifests claim more than their records support:\n${problems.map((problem) => `  ${problem}`).join("\n")}`);
    return 1;
  }
  const next = renderMatrix(checked);
  if (argv.includes("--write")) {
    writeFileSync(OUT, next);
    return 0;
  }
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== next) {
    console.error(`${OUT} is stale: run node scripts/gen-harness-matrix.mjs --write`);
    return 1;
  }
  return 0;
}

process.exitCode = await main(process.argv.slice(2));
