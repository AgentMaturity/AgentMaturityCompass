#!/usr/bin/env node
/**
 * P1-40: the public API of `agent-maturity-compass/sdk/native` as a committed snapshot (sdk/api/native.api.md).
 *
 * Generated from the built declarations (dist/sdk/nativeAgentClient.d.ts): every exported name, sorted, with its
 * declaration (comments, private members and @internal members removed) and its stability, `public` when the
 * declaration carries @public and `experimental` otherwise. The check fails when the snapshot is stale, and when the
 * branch changed the snapshot against its base without a changeset that mentions `sdk-api`. The semver policy is in
 * docs/sdk/TYPESCRIPT_SDK.md.
 *
 *   node scripts/check-sdk-api.mjs [--write] [--base-ref <ref>]
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const SNAPSHOT_PATH = "sdk/api/native.api.md";
export const DECLARATIONS_PATH = "dist/sdk/nativeAgentClient.d.ts";
const require = createRequire(import.meta.url);

const tags = (ts, node) => ts.getJSDocTags(node).map((tag) => tag.tagName.text);
const hidden = (ts, member) => tags(ts, member).includes("internal") || (member.name && ts.isPrivateIdentifier(member.name))
  || (ts.getCombinedModifierFlags(member) & ts.ModifierFlags.Private) !== 0;

/** The snapshot for the declarations at `dtsPath`; `text`, when given, replaces that file's content (tests). */
export function renderSdkApi(dtsPath, text) {
  const ts = require("typescript");
  const file = resolve(dtsPath);
  const options = { noEmit: true, skipLibCheck: true, types: ["node"] };
  const host = ts.createCompilerHost(options);
  if (text !== undefined) {
    const read = host.getSourceFile;
    host.getSourceFile = (name, version, ...rest) =>
      resolve(name) === file ? ts.createSourceFile(name, text, version, true) : read.call(host, name, version, ...rest);
  }
  const program = ts.createProgram([file], options, host);
  const checker = program.getTypeChecker();
  const printer = ts.createPrinter({ removeComments: true });
  const sections = checker.getExportsOfModule(checker.getSymbolAtLocation(program.getSourceFile(file))).map((exported) => {
    const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    const declarations = symbol.declarations ?? [];
    const experimentalMembers = [];
    const body = declarations.map((d) => {
      if (ts.isSourceFile(d)) return `namespace ${exported.name} { ${checker.getExportsOfModule(symbol).map((s) => s.name).sort().join(", ")} }`;
      let node = ts.isVariableDeclaration(d) ? d.parent.parent : d;
      if (ts.isClassDeclaration(d)) {
        const members = d.members.filter((m) => !hidden(ts, m));
        experimentalMembers.push(...members.filter((m) => tags(ts, m).includes("experimental")).map((m) => m.name.getText()));
        node = ts.factory.updateClassDeclaration(d, d.modifiers, d.name, d.typeParameters, d.heritageClauses, members);
      }
      return printer.printNode(ts.EmitHint.Unspecified, node, d.getSourceFile());
    }).join("\n");
    const stability = declarations.some((d) => tags(ts, d).includes("public")) ? "public" : "experimental";
    return { name: exported.name, stability, body, experimentalMembers: experimentalMembers.sort() };
  }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  return [
    "# API snapshot: agent-maturity-compass/sdk/native",
    "",
    `Generated by \`node scripts/check-sdk-api.mjs --write\` from \`${DECLARATIONS_PATH}\`; do not edit by hand.`,
    "`public` names follow the semver policy in docs/sdk/TYPESCRIPT_SDK.md; `experimental` names and members may change in",
    "a minor release with a changeset note.",
    "",
    ...sections.flatMap((s) => [`## ${s.name} (${s.stability})`, "",
      ...(s.experimentalMembers.length ? [`Experimental members: ${s.experimentalMembers.join(", ")}.`, ""] : []),
      "```ts", s.body, "```", ""])
  ].join("\n");
}

/**
 * `committed` is the snapshot in the tree (null when missing); `base` the base ref's (null when it has none, undefined
 * when the base ref does not resolve); `changesetTexts` the changesets this branch added or modified.
 */
export function evaluateSdkApi({ generated, committed, base, changesetTexts }) {
  const failures = [];
  const regenerate = `run "node scripts/check-sdk-api.mjs --write", review the diff and add a changeset that mentions sdk-api`;
  if (committed === null) failures.push(`${SNAPSHOT_PATH} is missing: ${regenerate}.`);
  else if (generated !== committed) failures.push(`${SNAPSHOT_PATH} does not match ${DECLARATIONS_PATH}: ${regenerate}.`);
  if (committed !== null && base !== undefined && committed !== base && !changesetTexts.some((text) => /\bsdk-api\b/.test(text))) {
    failures.push(`${SNAPSHOT_PATH} changed against the base, and no changeset changed by this branch mentions sdk-api.`);
  }
  return { ok: failures.length === 0, failures };
}

function git(args, cwd) {
  const result = spawnSync("git", args, { cwd, encoding: "utf8" });
  return result.status === 0 ? result.stdout : null;
}

/** The base ref's snapshot and the texts of changesets changed since the merge base (as scripts/check-freeze.mjs reads them). */
function loadBase(root, baseRef) {
  const base = git(["rev-parse", "--verify", "--quiet", `${baseRef}^{commit}`], root)?.trim();
  if (!base) return { base: undefined, changesetTexts: [], notice: `Base ref ${baseRef} does not resolve; exact check only.` };
  const mergeBase = git(["merge-base", base, "HEAD"], root)?.trim() || base;
  const changed = git(["diff", "--name-only", "--diff-filter=AM", mergeBase, "HEAD", "--", ".changeset"], root) ?? "";
  const changesetTexts = changed.split("\n").filter((f) => f.endsWith(".md") && existsSync(join(root, f))).map((f) => readFileSync(join(root, f), "utf8"));
  return { base: git(["show", `${base}:${SNAPSHOT_PATH}`], root), changesetTexts, notice: null };
}

function main(args) {
  const root = process.cwd();
  if (!existsSync(join(root, DECLARATIONS_PATH))) throw new Error(`Build first: ${DECLARATIONS_PATH} not found (pnpm run build).`);
  const generated = renderSdkApi(join(root, DECLARATIONS_PATH));
  const snapshot = join(root, SNAPSHOT_PATH);
  if (args.includes("--write")) {
    mkdirSync(dirname(snapshot), { recursive: true });
    writeFileSync(snapshot, generated);
    console.log(`Wrote ${SNAPSHOT_PATH}`);
    return 0;
  }
  const at = args.indexOf("--base-ref");
  const baseRef = at >= 0 ? args[at + 1] : process.env.GITHUB_BASE_REF ? `origin/${process.env.GITHUB_BASE_REF}` : "origin/main";
  const { base, changesetTexts, notice } = loadBase(root, baseRef);
  if (notice) console.log(`notice: ${notice}`);
  const result = evaluateSdkApi({ generated, committed: existsSync(snapshot) ? readFileSync(snapshot, "utf8") : null, base, changesetTexts });
  for (const failure of result.failures) console.error(failure);
  if (result.ok) console.log(`SDK API snapshot matches ${DECLARATIONS_PATH}.`);
  return result.ok ? 0 : 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  process.exit(main(process.argv.slice(2)));
}
