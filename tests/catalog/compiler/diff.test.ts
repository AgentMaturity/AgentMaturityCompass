describe("compiler fact-driven diffs", () => {
  test("one entity fact removes only the synthetic US duty and has an explicit Markdown contract", () => {
    const fixture = createCompilerFixture();
    try {
      const before = compilePlan({ catalog: fixture.catalog, profile: fixture.profile, asOf: AS_OF });
      const after = compilePlan({ catalog: fixture.catalog, asOf: AS_OF, profile: makeProfile({ entityTypes: {
        value: ["hipaa_covered_entity"], provenance: "asserted", source: "fixture: synthetic entity change", reviewedBy: null
      } }) });
      expect(after.digest).not.toBe(before.digest);
      expect(before.status).toBe("ready");
      expect(after.status).toBe("ready");
      const diff = diffPlans(before, after);
      expect(diff).toEqual(expectedEntityDiff(before.digest));
      expect(renderPlanDiffMarkdown(diff)).toBe(expectedMarkdown(before.digest));
    } finally { fixture.cleanup(); }
  });

  test("identical fact inputs have no semantic diff and the absent-previous renderer is explicit", () => {
    const fixture = createCompilerFixture();
    try {
      const before = compilePlan({ catalog: fixture.catalog, profile: fixture.profile, asOf: AS_OF });
      const after = compilePlan({ catalog: fixture.catalog, profile: fixture.profile, asOf: AS_OF });
      expect(diffPlans(before, after)).toEqual({
        previousDigest: before.digest, requirements: [], runtimePolicy: [], evidencePlan: [],
        conflicts: [], mergeRules: [], mergeExceptionRejected: []
      });
      expect(renderPlanDiffMarkdown(null)).toBe("# Control plan diff\n\nNo previous plan was given, so there is nothing to compare.\n");
    } finally { fixture.cleanup(); }
  });
});
