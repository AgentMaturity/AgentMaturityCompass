  "    if (posted.status === 200 || posted.status === 201) paymentId = posted.json?.paymentId ?? null;",
  "    else paymentId = (await call(\"GET\", `/v1/payments?idempotencyKey=${plan.key}`)).json?.payments?.[0]?.paymentId ?? null;",
  "  }",
  "  result = { status: paymentId ? \"committed\" : \"unknown\", paymentIds: paymentId ? [paymentId] : [], discrepancies: [] };",
  "}",
  "if (plan.reconcile) {",
  "  const bank = (await call(\"GET\", \"/v1/bank-transactions\")).json?.bankTransactions ?? [];",
